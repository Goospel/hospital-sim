// 전환 회귀 픽스처 — **rooms 기반과 영역 기반이 같은 세계를 낳는가**의 단일 계측기.
//
// 설계(2026-07-28 freeform-build) PR 1b의 계약은 하나다: *시뮬 규칙·수치는 동작 무변*.
// 소비자를 하나씩 옮기는 동안 어느 한 곳이 조용히 다른 자리를 고르면(방 열거 순서·좌석
// 선택·경로) 그 차이는 예외가 아니라 **숫자로만** 나타난다 — 진료 한 건, 좌표 한 칸.
// 그래서 값은 전환 **전**(HEAD = cb7f3b9, 1a 직후)에서 실측해 박아 둔다. 손으로 계산한
// 기대값이 아니라 옛 구현의 출력이라, 이 파일이 죽으면 전환이 틀린 것이다.
//
// ⚠️ **2026-07-29에 세 번 다시 박았다.** 값만 갈아치우면 다음 사람이 "언제 왜 갈렸는지"를
// 영영 못 찾으므로 이력을 남긴다. 셋 다 전환 무변 계약의 위반이 아니라 **의도한 규칙 변경**이다.
//   ① "의자에 앉는다"(사용자 지시) — 의자가 통행 가능해지고 좌석이 의자 **앞**에서 의자
//      **그 자체**로 옮겨졌다. `examsDone 3→4 · leftCount 37→36 · revenue 36→48`.
//      원인 둘: 의자가 안 막아 대기실 보행이 짧아졌다 · 좌석이 겹칠 수 없어져 자리 선택이 갈렸다.
//   ② "접수처 반려"(사용자 지시 — *"내과가 없는데 내과 환자가 대기실에서 기다린다"*) —
//      안 보는 과 환자가 대기실에 안 들어온다. `examsDone 4→7 · leftCount 36→33 · revenue 48→84`.
//      **진료가 75% 늘어난 것이 이 변경의 크기다**: 이 병원은 내과 하나뿐이라 도착의 55%가
//      문 앞에서 돌아가는데, 그 55%가 예전엔 의자 6석을 90분씩 물고 있어 **볼 수 있었던 내과
//      환자까지 문간에서 밀어냈다**. 좌석이 풀리자 같은 의사 한 명이 3건을 더 봤다.
//   ③ "수납"(설계 2026-07-29 · 간호사 + 접수처 카운터) — **수납 창구가 없는 병원은 이제 표준이
//      아니다.** 진료비는 간호사가 지키는 접수처 카운터에서만 걷히므로, 창구 없는 옛 픽스처는
//      그대로 돌리면 수입이 **0**이 되고 그 84만원이 통째로 `stats.unpaidManwon`으로 샌다 —
//      즉 값을 안 고치면 이 파일은 "돈이 도는가"를 더 이상 재지 못한다. 그래서 픽스처에
//      **접수처 + 카운터 + 간호사 1명**을 더했다(testHelpers.withCashier).
//      `revenueManwon 84→72`. **환자 흐름은 한 톨도 안 갈렸다**: `examsDone 7 · leftCount 33 ·
//      leftNoDept 32`가 전부 그대로다(창구는 도착·좌석·배정 어디에도 안 낀다). 줄어든 12는
//      **미수가 아니라 아직 안 낸 돈**이다 — 300분 시점에 7번째 환자가 카운터로 걸어가는
//      중이라(`31,20`) 그 한 건이 아직 금고 밖이고, 실제로 `unpaidManwon === 0`이다.
//      pawnTiles 변화도 그 한 사람과 간호사뿐이다: `26,25`(입구로 나가던 사람)가 `31,20`
//      (카운터로 가는 같은 사람)으로 옮겨가고 `42,25`(카운터 앞의 간호사)가 늘었다.
//      ⓘ 폰 **id**는 한 칸씩 밀렸다(`pat-8`→`pat-9` …) — 간호사가 `nextId`를 하나 쓴다.
//        id는 이 단언이 보는 축이 아니라(좌표만 본다) 값에는 영향이 없다.
import { describe, it, expect } from 'vitest'
import { createWorld } from './world'
import { tick } from './tick'
import { hire, placeRoom, withCashier } from './testHelpers'

/** 대기실 + 진료실(내과) + 병동 + **수납 창구**(접수처·카운터·간호사) + 내과 의사 1명 —
 *  외래 한 줄이 **돈까지 되는** 최소 병원(각주 ③). */
function hospital() {
  let w = createWorld(7)
  for (const spec of [
    { type: 'WAITING' as const, x: 18, y: 24, w: 8, h: 6 },
    { type: 'EXAM' as const, dept: 'INTERNAL_MEDICINE' as const, x: 18, y: 14, w: 8, h: 6 },
    { type: 'WARD' as const, x: 28, y: 14, w: 8, h: 6 },
  ]) {
    const r = placeRoom(w, spec)
    if (!r.ok) throw new Error(`전제 실패 — 건설 거부(${r.reason})`)
    w = r.world
  }
  return withCashier(hire(w, 'INTERNAL_MEDICINE'))
}

describe('영역 전환 회귀 — 300분을 돌린 세계가 전환 전과 같다', () => {
  it('집계·수입·폰 좌표가 전환 전 실측값과 일치한다', () => {
    const w0 = hospital()
    const w = tick(w0, 300)
    // ↓ 전환 **전**(1a HEAD = cb7f3b9)에서 실측해 박은 값이다. 손으로 맞추지 말 것 —
    //   값이 달라졌다면 테스트가 아니라 전환이 틀린 것이다.
    //   한 덩어리로 단언하는 이유: 네 축이 갈라져 있으면 첫 축에서 멈춰 나머지 어긋남이 안 보인다.
    expect({
      examsDone: w.stats.examsDone,
      leftCount: w.stats.leftCount,
      leftNoDept: w.stats.leftNoDept,
      // **건설비가 아니라 300분 동안의 수입**을 잰다 — 비용표는 튜닝 대상이고(build.BUILD_COST)
      // 그게 바뀔 때마다 이 픽스처가 우는 건 회귀가 아니라 잡음이다. 시뮬이 낳은 값은 차액뿐이다.
      revenueManwon: w.treasuryManwon - w0.treasuryManwon,
      // 걷힌 돈만 재면 "수납 창구가 통째로 죽어 전액이 샜다"와 "회전이 느려 덜 벌었다"가
      // 같은 숫자로 보인다 — 미수를 나란히 박아 그 둘을 갈라 둔다(각주 ③).
      unpaidManwon: w.stats.unpaidManwon,
      pawnTiles: w.pawns.map(p => `${p.x},${p.y}`).sort(),
    }).toEqual({
      examsDone: 7,
      // 33건 중 **32건이 접수처 반려**다(아래) — 남는 1건만 좌석 부족·인내 초과다.
      // 이 대비가 이번 변경의 요점이다: 놓친 사람의 사유가 "의자가 모자라서"에서 **"그 과가
      // 없어서"**로 정확히 옮겨 갔다(더 지어도 안 줄고, 채용해야 줄어드는 손실).
      leftCount: 33,
      // 반려는 이탈의 **부분집합**이다 — 이 값이 leftCount를 넘으면 어딘가에서 두 번 세고 있다.
      leftNoDept: 32,
      // 72 = 6건 × 내과 수가 12. 7번째는 **미수가 아니라 아직 걷는 중**이다(각주 ③) —
      // 아래 `unpaidManwon`이 그 구별을 진다: 0이면 샌 돈이 없다는 뜻이다.
      revenueManwon: 72,
      unpaidManwon: 0,
      // 의자 6석은 **전부 내과 대기자**다 — (19,25)·(19,27)·(21,25)·(21,27)·(23,25)·(23,27).
      // (19,16)은 책상 앞의 의사, (26,26)은 방금 들어와 걸어오는 중인 환자.
      // (31,20)은 진료를 마치고 **카운터로 가는 중**, (42,25)는 그 카운터 앞의 간호사다.
      // 300분 시점에 진료 의자(20,15)가 빈 것도 결과다 — 회전이 빨라져 그 순간 사이가 떴다.
      pawnTiles: ['19,16', '19,25', '19,27', '21,25', '21,27', '23,25', '23,27', '26,26', '31,20', '42,25'],
    })
  })
})
