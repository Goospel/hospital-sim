import { fileURLToPath } from 'node:url'
import { defineConfig } from 'vitest/config'

/**
 * vitest 설정 — **`.claude/worktrees/`를 테스트 대상에서 제외하는 게 이 파일의 존재 이유다.**
 *
 * 설정 파일이 없던 동안 vitest 기본 include(`**\/*.test.ts`)가 `.claude/worktrees/` 안의
 * **버려진 워크트리들**까지 잡아, 이 레포의 테스트 12파일 220건이 **33파일 510건**으로 보고됐다.
 * 초과분은 전부 **옛 코드를 대상으로 도는 옛 테스트**다 — green이어도 main에 대해 아무 말도 안 한다.
 *
 * 위험한 건 숫자가 틀린 것 자체가 아니라 **신뢰의 희석**이다:
 *   - "510 green"이 커밋 메시지에 박히면 나중에 아무도 검증 못 한다(그때 워크트리가 몇 개였는지 모른다).
 *   - 워크트리의 낡은 테스트가 실패하면 멀쩡한 작업이 막히고, 원인 추적에 시간이 든다.
 *   - 기본 exclude는 `node_modules`·`dist`만 막는다. `.claude/`는 아무도 안 막아준다.
 *
 * ⚠️ 워크트리 자체는 지우지 않는다 — 이전 세션의 작업이 들어 있을 수 있다(T-030 계열).
 * 테스트 대상에서 빼기만 한다.
 */
export default defineConfig({
  /** `@/*` → `src/*` — tsconfig의 paths와 같은 계약. 이게 없으면 `@/`로 import하는 **소스 파일**을
   *  테스트가 아예 못 불러온다(테스트가 상대경로만 써도 소용없다 — 대상 모듈이 걸린다). */
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  test: {
    include: ['src/**/*.{test,spec}.{ts,tsx}'],
    exclude: ['**/node_modules/**', '**/.claude/**', '**/.next/**'],
    /**
     * 스위트 전체가 **시드 결정론**이라 타임아웃의 유일한 역할은 **무한 루프 감지**다 —
     * "느려서 실패"는 이 저장소에서 신호가 아니라 잡음이다.
     *
     * vitest 기본 5초는 무거운 주간 시뮬 테스트(단독 실측 3.2초)가 **전체 스위트의
     * fork 병렬 CPU 경합**에서 넘겨 간헐 실패를 냈다 — 단독 실행은 늘 통과하는데
     * 51파일을 한 번에 돌리면 5~6건이 무작위로 죽었다(실패 목록은 언제나 그 파일의
     * **최슬로우 테스트들**과 일치했고, 전부 `Test timed out in 5000ms`였다).
     * 경합을 3배로 키워 재현하니 같은 테스트들이 최악 **18.7초**까지 늘어졌다.
     *
     * 60초는 그 여유를 주면서 무한 루프 감지는 유지한다. 자세한 경위: T-155.
     */
    testTimeout: 60_000,
  },
})
